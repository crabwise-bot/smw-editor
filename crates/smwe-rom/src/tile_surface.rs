//! Lunar Magic "Tile Surface Outlines" view data (LM v3.00; water tiles v3.70).
//!
//! The slope tables below are byte-exact copies of the game's own data from
//! SMWDisX `bank_00.asm`:
//! * `SLOPE_IDS_DEFAULT` = `DATA_00E55E`: tile low-byte (`0x6E..=0xD7`) -> slope ID.
//! * `SLOPE_IDS_TILESET_0_7` = `DATA_00E5C8`: the alternate mapping the game
//!   installs for object tilesets 0 and 7 (bank_05.asm `CODE_0581FB`/
//!   `CODE_058281`; those tilesets also gain diagonal-pipe slope tiles).
//! * `SLOPE_HEIGHTS` = `SlopeHeights`: 16 surface-height bytes per slope ID,
//!   indexed by the game as `SlopeHeights[slope_id * 16 + x]` where `x` is the
//!   intra-tile pixel column (bank_00.asm `CODE_00FA19` / `CODE_00ECDA`).
//!   Heights `$00..=$10` are floor slopes (surface `y` px from the tile top;
//!   `$10` = fully solid column); heights `$F0..=$FF` are flipped (ceiling)
//!   slopes, whose surface sits at `0x0F - (raw & 0x0F)` px from the top.
//!
//! Provenance notes and honest limits:
//! * Only slope IDs `0x00..=0x1E` have a complete 16-byte profile in the ROM;
//!   ID `0x1F` (Map16 tile `0x1CD`) is truncated to 6 bytes in `SlopeHeights`
//!   (the disassembly's table ends mid-chunk) and has no defined outline —
//!   the tile falls back to a plain solid outline.
//! * Hurt-block membership follows the game's own dispatch (`CODE_00F127`,
//!   called with the tile's low byte, which `JSL HurtMario`s) plus the lava /
//!   magma tiles this crate already documents in `block_behavior`.
//!   Lunar Magic's exact red set is not in the public docs; this implements
//!   the game-grounded set.
//! * Water membership follows the game's liquid check (`RunPage0Blocks_2`:
//!   "Liquid? (0-5)"). Tiles `0x004`/`0x005` are both liquid and lava; hurt
//!   (red) wins over water (blue) for those.

