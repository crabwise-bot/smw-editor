/// Tile low-byte -> slope ID for object tilesets 0 and 7 (SMWDisX `DATA_00E5C8`).
const SLOPE_IDS_TILESET_0_7: [u8; 106] = SLOPE_IDS_ALT_RAW;

const SLOPE_TABLE_LO: u8 = 0x6E;
const SLOPE_TABLE_HI: u8 = 0xD7;

/// Slope ID for a slope-range tile low-byte, honouring the game's
/// tileset-dependent table selection. Returns `None` outside `0x6E..=0xD7`.
pub fn slope_id_for(tile_low: u8, object_tileset: u8) -> Option<u8> {
    if !(SLOPE_TABLE_LO..=SLOPE_TABLE_HI).contains(&tile_low) {
        return None;
    }
    let table = if object_tileset == 0 || object_tileset == 7 { &SLOPE_IDS_TILESET_0_7 } else { &SLOPE_IDS_DEFAULT };
    Some(table[(tile_low - SLOPE_TABLE_LO) as usize])
}

/// Number of complete 16-byte slope profiles in [`SLOPE_HEIGHTS`].
pub const SLOPE_PROFILE_COUNT: u8 = (SLOPE_HEIGHTS.len() / 16) as u8;

/// Raw 16-byte surface-height profile for a slope ID, or `None` when the ROM
/// has no complete profile for it (slope ID `0x1F`).
pub fn slope_heights_raw(slope_id: u8) -> Option<[u8; 16]> {
    if slope_id >= SLOPE_PROFILE_COUNT {
        return None;
    }
    let base = slope_id as usize * 16;
    let mut out = [0u8; 16];
    out.copy_from_slice(&SLOPE_HEIGHTS[base..base + 16]);
    Some(out)
}

/// Surface height in pixels from the tile top (0..=16) for one raw
/// `SlopeHeights` byte. Floor slopes store the height directly (`$10` = one
/// past the tile bottom, i.e. a fully solid column); flipped (ceiling) slopes
/// store `$F0..=$FF` and the surface sits at `0x0F - (raw & 0x0F)`.
pub fn surface_px_height(raw: u8) -> u8 {
    if raw <= 0x10 {
        raw
    } else {
        0x0F - (raw & 0x0F)
    }
}

/// 16 per-pixel-column surface heights (px from the tile top) for a
/// slope-range tile low-byte, or `None` if it has no defined profile.
pub fn slope_surface_px(tile_low: u8, object_tileset: u8) -> Option<[u8; 16]> {
    let id = slope_id_for(tile_low, object_tileset)?;
    let raw = slope_heights_raw(id)?;
    Some(raw.map(surface_px_height))
}

/// Act-as roots the game treats as liquid ("Liquid? (0-5)" in
/// `RunPage0Blocks_2`, SMWDisX bank_00.asm). Lunar Magic v3.70 draws these in
/// the Tile Surface Outlines view.
pub fn is_water_tile(acts_root: u16) -> bool {
    matches!(acts_root, 0x000..=0x005)
}

/// Whether an act-as root hurts Mario on contact (Lunar Magic draws these red
/// in Tile Surface Outlines).
///
/// * The low-byte sets come from the game's own hurt dispatch (SMWDisX
///   bank_00.asm `CODE_00F127`, entered with the tile's low byte in A):
///   `0x2F` always; `0x59..=0x5B` on object tilesets `0x05`/`0x0D`;
///   `0x5C` and `0x66..=0x69` on object tileset `0x01`.
/// * `0x004`/`0x005` (lava surface/subsurface) and `0x1FB..=0x1FF` (magma
///   inside) are the documented lava tiles (`block_behavior::specific_behavior`;
///   `0x005` "kills Mario if feet touch it").
pub fn is_hurt_tile(acts_root: u16, object_tileset: u8) -> bool {
    match acts_root {
        0x004 | 0x005 => true,
        0x1FB..=0x1FF => true,
        _ => {
            let low = (acts_root & 0xFF) as u8;
            match low {
                0x2F => true,
                0x59..=0x5B => object_tileset == 0x05 || object_tileset == 0x0D,
                0x5C | 0x66..=0x69 => object_tileset == 0x01,
                _ => false,
            }
        }
    }
}

/// What Lunar Magic's Tile Surface Outlines view draws for a tile.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SurfaceKind {
    /// Solid tile (incl. ledges and slope-assist): rectangular outline.
    Solid,
    /// Slope tile: per-pixel-column surface heights (px from the tile top),
    /// drawn as the surface polyline.
    Slope([u8; 16]),
    /// Water tile (LM v3.70).
    Water,
    /// Hurt block (drawn red).
    Hurt,
}

/// The Tile Surface Outlines marking for an act-as root, or `None` for tiles
/// with no surface (non-solid, extended/custom). Priority: hurt beats water
/// (lava `0x004`/`0x005` are both), then water, then slope, then solid.
pub fn surface_kind(acts_root: u16, object_tileset: u8) -> Option<SurfaceKind> {
    if is_hurt_tile(acts_root, object_tileset) {
        return Some(SurfaceKind::Hurt);
    }
    if is_water_tile(acts_root) {
        return Some(SurfaceKind::Water);
    }
    let low = (acts_root & 0xFF) as u8;
    match acts_root {
        // Slope range: draw the game's own surface profile.
        0x16E..=0x1D7 => match slope_surface_px(low, object_tileset) {
            Some(px) => Some(SurfaceKind::Slope(px)),
            // Truncated profile (slope ID 0x1F): solid outline instead.
            None => Some(SurfaceKind::Solid),
        },
        // Ledges, solids, and slope-assist: rectangular outline.
        0x100..=0x16D | 0x1D8..=0x1FF => Some(SurfaceKind::Solid),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn slope_tables_cover_the_game_range() {
        assert_eq!(SLOPE_IDS_DEFAULT.len(), 0xD8 - 0x6E);
        assert_eq!(SLOPE_IDS_TILESET_0_7.len(), 0xD8 - 0x6E);
        // 31 complete 16-byte profiles + 14 trailing bytes of the truncated ID 0x1F.
        assert_eq!(SLOPE_HEIGHTS.len(), 31 * 16 + 14);
        assert_eq!(SLOPE_PROFILE_COUNT, 31);
    }

    #[test]
    fn slope_id_spot_checks() {
        // First/last tiles of the slope range, default table.
        assert_eq!(slope_id_for(0x6E, 1), Some(0x00));
        assert_eq!(slope_id_for(0xAA, 1), Some(0x0C)); // Map16 0x1AA: 1:1 slope up
        assert_eq!(slope_id_for(0xC4, 1), Some(0x12)); // Map16 0x1C4: flipped slope
        assert_eq!(slope_id_for(0xCC, 1), Some(0x1E));
        assert_eq!(slope_id_for(0xCD, 1), Some(0x1F)); // truncated profile
        assert_eq!(slope_id_for(0xD7, 1), Some(0x0D));
        // Outside the range: none.
        assert_eq!(slope_id_for(0x6D, 1), None);
        assert_eq!(slope_id_for(0xD8, 1), None);
        // Tilesets 0 and 7 use the alternate table: the diagonal-pipe tiles
        // 0xC4..=0xC7 are flipped slopes by default, plain slopes there.
        assert_eq!(slope_id_for(0xC4, 1), Some(0x12));
        assert_eq!(slope_id_for(0xC4, 0), Some(0x0C));
        assert_eq!(slope_id_for(0xC4, 7), Some(0x0C));
        assert_eq!(slope_id_for(0xB6, 1), Some(0x10));
        assert_eq!(slope_id_for(0xB6, 0), Some(0x10));
    }

    #[test]
    fn slope_profile_shapes_match_the_game() {
        // 1:4 slope up (ID 0x00): gentle fall left-to-right, 15..=12.
        let gentle = slope_heights_raw(0x00).unwrap();
        assert_eq!(gentle[0], 0x0F);
        assert_eq!(gentle[15], 0x0C);
        // 1:1 slope up (ID 0x0C): surface falls left-to-right, 15..=0.
        let up = slope_heights_raw(0x0C).unwrap();
        assert_eq!(up[0], 0x0F);
        assert_eq!(up[15], 0x00);
        // 1:1 slope down (ID 0x0D): rises left-to-right, 0..=15.
        let down = slope_heights_raw(0x0D).unwrap();
        assert_eq!(down[0], 0x00);
        assert_eq!(down[15], 0x0F);
        // Flipped (ceiling) slopes are the high range.
        let flip = slope_heights_raw(0x12).unwrap();
        assert!(flip.iter().all(|&b| b >= 0xF0));
        // Truncated ID 0x1F: no profile.
        assert_eq!(slope_heights_raw(0x1F), None);
    }

    #[test]
    fn px_height_mapping() {
        assert_eq!(surface_px_height(0x00), 0);
        assert_eq!(surface_px_height(0x0F), 15);
        assert_eq!(surface_px_height(0x10), 16);
        // Flipped: 0x0F - (raw & 0x0F).
        assert_eq!(surface_px_height(0xFF), 0);
        assert_eq!(surface_px_height(0xF0), 15);
        // 1:1 flipped slope down (ID 0x12, tile 0x1C4): the ceiling surface
        // descends left-to-right: top-left to bottom-right.
        let px = slope_surface_px(0xC4, 1).unwrap();
        assert_eq!(px[0], 0);
        assert_eq!(px[15], 15);
        // 1:1 slope up (ID 0x0C, tile 0x1AA): floor surface, same geometry.
        let floor = slope_surface_px(0xAA, 1).unwrap();
        assert_eq!(floor[0], 15);
        assert_eq!(floor[15], 0);
    }

    #[test]
    fn water_and_hurt_sets() {
        for id in 0x000..=0x005u16 {
            assert!(is_water_tile(id), "{id:#X} should be water");
        }
        assert!(!is_water_tile(0x006));
        assert!(!is_water_tile(0x100));
        // Lava is both liquid and hurt; hurt wins in surface_kind.
        assert!(is_hurt_tile(0x004, 1));
        assert!(is_hurt_tile(0x005, 1));
        assert!(is_hurt_tile(0x1FB, 1));
        assert!(is_hurt_tile(0x1FF, 1));
        assert!(!is_hurt_tile(0x1FA, 1));
        // CODE_00F127 low-byte sets.
        assert!(is_hurt_tile(0x02F, 1));
        assert!(is_hurt_tile(0x12F, 3)); // page-1 solid with spike low byte
        assert!(is_hurt_tile(0x059, 0x05));
        assert!(is_hurt_tile(0x05B, 0x0D));
        assert!(!is_hurt_tile(0x059, 0x01));
        assert!(is_hurt_tile(0x05C, 0x01));
        assert!(!is_hurt_tile(0x05C, 0x02));
        assert!(is_hurt_tile(0x066, 0x01));
        assert!(is_hurt_tile(0x069, 0x01));
        assert!(!is_hurt_tile(0x066, 0x02));
        assert!(!is_hurt_tile(0x030, 1));
    }

    #[test]
    fn surface_kind_priorities() {
        // Lava 0x004: hurt beats water.
        assert_eq!(surface_kind(0x004, 1), Some(SurfaceKind::Hurt));
        assert_eq!(surface_kind(0x002, 1), Some(SurfaceKind::Water));
        // Ordinary slope: polyline.
        assert!(matches!(surface_kind(0x16E, 1), Some(SurfaceKind::Slope(_))));
        // Truncated slope ID 0x1F (tile 0x1CD): solid fallback.
        assert_eq!(surface_kind(0x1CD, 1), Some(SurfaceKind::Solid));
        // Solid / ledge / slope-assist: solid outline.
        assert_eq!(surface_kind(0x130, 1), Some(SurfaceKind::Solid));
        assert_eq!(surface_kind(0x106, 1), Some(SurfaceKind::Solid));
        assert_eq!(surface_kind(0x1E0, 1), Some(SurfaceKind::Solid));
        // Non-solid / extended: nothing.
        assert_eq!(surface_kind(0x025, 1), None);
        assert_eq!(surface_kind(0x2A0, 1), None);
    }
}
